from random import choice

@bot.message_handler(commands=['/fact'])
def fact_handler(message):
    fact  = choice(["Живи так, как если бы тебе предстояло умереть завтра. Учись так, как будто тебе суждено жить вечно", "Надо любить жизнь больше, чем смысл жизни", "Жизнь измеряется не количеством наших вдохов, а количеством моментов, от которых перехватывает дыхание", "Стремитесь не к успеху, а к ценностям, которые он даёт"])
    bot.reply_to(message, fact)
